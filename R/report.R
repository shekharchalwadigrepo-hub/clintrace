#' Generate a polished HTML lineage report
#'
#' @param trace A clintrace object.
#' @param file Character. Output HTML file path. If NULL, returns HTML as character.
#' @param title Character. Report title.
#' @param study_info Optional list with extra study metadata to display.
#'
#' @return Path to the HTML file (invisibly) or HTML string.
#' @export
trace_report <- function(trace,
                         file = NULL,
                         title = "Clinical Data Lineage Report",
                         study_info = list()) {
  if (!inherits(trace, "clintrace")) stop("Not a clintrace object")
  if (!requireNamespace("knitr", quietly = TRUE)) {
    stop("Package 'knitr' is required. Install with install.packages('knitr')")
  }
  if (!requireNamespace("htmltools", quietly = TRUE)) {
    stop("Package 'htmltools' is required.")
  }

  recs <- trace$records
  n <- nrow(recs)
  val <- validate_trace(trace)

  # Summary cards
  summary_html <- htmltools::tags$div(
    class = "summary-grid",
    htmltools::tags$div(class = "card",
      htmltools::tags$div(class = "card-value", n),
      htmltools::tags$div(class = "card-label", "Lineage Records")
    ),
    htmltools::tags$div(class = "card",
      htmltools::tags$div(class = "card-value", length(unique(recs$target_variable))),
      htmltools::tags$div(class = "card-label", "Variables Traced")
    ),
    htmltools::tags$div(class = "card",
      htmltools::tags$div(
        class = paste("card-value", if (val$valid) "ok" else "warn"),
        if (val$valid) "PASS" else "ISSUES"
      ),
      htmltools::tags$div(class = "card-label", "Validation")
    )
  )

  # Main table
  if (n == 0) {
    table_html <- htmltools::tags$p("No lineage records recorded.")
  } else {
    show_cols <- c("step_id", "target_dataset", "target_variable",
                   "source_dataset", "source_variable", "derivation_type",
                   "algorithm", "keys")
    show <- recs[, intersect(show_cols, names(recs))]
    table_html <- htmltools::HTML(
      knitr::kable(show, format = "html", escape = TRUE,
                   table.attr = "class='lineage-table'")
    )
  }

  # Issues section
  issues_html <- if (val$n_issues > 0) {
    htmltools::tags$div(
      htmltools::tags$h2("Validation Issues"),
      htmltools::HTML(knitr::kable(val$issues, format = "html", escape = TRUE))
    )
  } else {
    htmltools::tags$p(class = "ok-msg", "No validation issues found.")
  }

  meta_items <- c(
    list(
      "Study ID" = trace$study_id %||% "<not set>",
      "Created"  = format(trace$created),
      "Generated"= format(Sys.time())
    ),
    study_info
  )

  meta_html <- htmltools::tags$div(
    class = "meta",
    lapply(names(meta_items), function(nm) {
      htmltools::tags$p(htmltools::tags$strong(paste0(nm, ": ")), meta_items[[nm]])
    })
  )

  css <- "
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
           margin: 40px; background: #f7fafc; color: #1a202c; }
    h1 { color: #1a365d; border-bottom: 3px solid #2b6cb0; padding-bottom: 8px; }
    h2 { color: #2c5282; margin-top: 32px; }
    .meta { background: white; padding: 16px 20px; border-radius: 8px;
            box-shadow: 0 1px 3px rgba(0,0,0,.1); margin-bottom: 24px; }
    .summary-grid { display: flex; gap: 16px; margin-bottom: 24px; flex-wrap: wrap; }
    .card { background: white; padding: 16px 24px; border-radius: 8px;
            box-shadow: 0 1px 3px rgba(0,0,0,.1); min-width: 140px; text-align: center; }
    .card-value { font-size: 28px; font-weight: 700; color: #2b6cb0; }
    .card-value.ok { color: #276749; }
    .card-value.warn { color: #c53030; }
    .card-label { font-size: 13px; color: #718096; margin-top: 4px; }
    .lineage-table { border-collapse: collapse; width: 100%; background: white;
                     border-radius: 8px; overflow: hidden; box-shadow: 0 1px 3px rgba(0,0,0,.1); }
    .lineage-table th { background: #2c5282; color: white; padding: 10px 12px; text-align: left; }
    .lineage-table td { padding: 8px 12px; border-bottom: 1px solid #e2e8f0; }
    .lineage-table tr:nth-child(even) { background: #f8fafc; }
    .ok-msg { color: #276749; font-weight: 600; }
  "

  html <- htmltools::tags$html(
    htmltools::tags$head(
      htmltools::tags$title(title),
      htmltools::tags$style(htmltools::HTML(css))
    ),
    htmltools::tags$body(
      htmltools::tags$h1(title),
      meta_html,
      summary_html,
      htmltools::tags$h2("Lineage Records"),
      table_html,
      issues_html,
      htmltools::tags$footer(
        style = "margin-top:40px; color:#a0aec0; font-size:12px;",
        "Generated by clintrace"
      )
    )
  )

  html_str <- as.character(html)

  if (is.null(file)) return(html_str)

  writeLines(html_str, file)
  message("Polished report written to: ", normalizePath(file))
  invisible(file)
}
